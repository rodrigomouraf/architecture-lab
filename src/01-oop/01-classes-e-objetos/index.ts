export class Casa {
    tamanhoM2: number;
    andares: number;
    valor: number;
    numeroVagas: number;

    constructor(tamanhoM2: number, andares: number, valor: number, numeroVagas: number) {
        this.tamanhoM2 = tamanhoM2;
        this.andares = andares;
        this.valor = valor;
        this.numeroVagas = numeroVagas;
    }
}